#!/usr/bin/env python3
"""Regenerate program-list.md from the public research results.

Input:  data/classification.tsv  (newsroom-style export of the public-policy sweep)
Output: program-list.md

Run from the repository root:  python3 scripts/build_program_list.py
"""
import csv
import os
from urllib.parse import urlparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def dedupe(rows):
    seen, out = {}, []
    for r in rows:
        key = (urlparse(r.get("policy_url") or "").netloc.lower().replace("www.", "")
               or r.get("host", ""))
        if key in seen:
            seen[key].append(r.get("host", ""))
            continue
        seen[key] = [r.get("host", "")]
        out.append((key, r))
    return out, seen


def quote(text):
    return " ".join((text or "").split()).replace("|", "\\|")[:240]


def main():
    rows = load(os.path.join(ROOT, "data", "classification.tsv"))

    paid = [r for r in rows if r.get("status") == "YES - DIRECT PAID BOUNTY"
            and r.get("confidence") == "HIGH"]
    vdp = [r for r in rows if r.get("status") == "YES - DIRECT VDP"
           and (r.get("policy_url") or "").startswith("http")]

    paid, aliases = dedupe(paid)
    vdp, v_aliases = dedupe(vdp)

    L = []
    a = L.append
    a("# Public bug-bounty programme list")
    a("")
    a("Organisations on this list publish a security page that invites external reports and")
    a("states either a reward or a disclosure process. Every entry links to the organisation's")
    a("own page. Nothing here is a third-party platform listing.")
    a("")
    a("Generated by `scripts/build_program_list.py` from `data/classification.tsv`.")
    a("")
    a(f"- Direct paid programmes: **{len(paid)}**")
    a(f"- Direct disclosure programmes (VDP): **{len(vdp)}**")
    a("")
    a("> A published policy is not blanket permission. Read each page before testing and")
    a("> respect its eligible-asset list and exclusions.")
    a("")
    a("## Direct paid programmes")
    a("")
    a("| # | Programme | Domains covered | Policy | Verbatim evidence |")
    a("|---|---|---|---|---|")
    for i, (key, r) in enumerate(paid, 1):
        names = ", ".join(aliases[key][:3])
        if len(aliases[key]) > 3:
            names += f" (+{len(aliases[key]) - 3})"
        a(f"| {i} | {key} | {names} | {r.get('policy_url', '')} | {quote(r.get('evidence'))} |")
    a("")
    a("## Direct disclosure programmes (no published reward)")
    a("")
    a("| # | Programme | Domains covered | Policy |")
    a("|---|---|---|---|")
    for i, (key, r) in enumerate(vdp, 1):
        names = ", ".join(v_aliases[key][:3])
        if len(v_aliases[key]) > 3:
            names += f" (+{len(v_aliases[key]) - 3})"
        a(f"| {i} | {key} | {names} | {r.get('policy_url', '')} |")
    a("")

    out = os.path.join(ROOT, "program-list.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print(f"[+] wrote {out}: {len(paid)} paid, {len(vdp)} VDP")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
